defmodule Authmk.Migration.Render do
  @moduledoc """
  Renders diff operations as an Ecto migration with `up/0` and `down/0`.
  `down/0` comes from diffing in the other direction, so it is exact.
  """

  alias Authmk.Migration.Diff

  @doc """
  Source code of a migration module. `adapter` is `:sqlite`, `:postgres` or
  `:mysql`. Raises when the adapter can't run an operation.
  """
  @spec migration(String.t(), [Diff.op()], [Diff.op()], atom()) :: String.t()
  def migration(module, up, down, adapter) do
    check_adapter!(up ++ down, adapter)

    """
    defmodule #{module} do
      use Ecto.Migration

      # Generated by `mix authmk.gen.migration`. Review it before running.

      def up do
    #{body(up)}
      end

      def down do
    #{body(down)}
      end
    end
    """
  end

  defp check_adapter!(ops, :sqlite) do
    for {:modify_column, table, column, _new, _old} <- ops do
      raise ArgumentError,
            "SQLite can't change existing columns, so #{table}.#{column} can't be modified. " <>
              "Rename the field to a new column instead, or rebuild the table by hand"
    end

    :ok
  end

  defp check_adapter!(_ops, adapter) when adapter in [:postgres, :mysql], do: :ok

  defp body([]), do: "    :ok"

  defp body(ops) do
    ops
    |> Enum.chunk_by(&alter_table/1)
    |> Enum.map_join("\n\n", &render_chunk/1)
    |> indent(4)
  end

  # Column operations on the same table share one `alter table` block.
  defp alter_table({op, table, _, _}) when op in [:add_column, :remove_column], do: table
  defp alter_table({:modify_column, table, _, _, _}), do: table
  defp alter_table(op), do: op

  defp render_chunk([{op, table, _, _} | _] = ops) when op in [:add_column, :remove_column],
    do: alter(table, ops)

  defp render_chunk([{:modify_column, table, _, _, _} | _] = ops), do: alter(table, ops)
  defp render_chunk([op]), do: render(op)

  defp alter(table, ops) do
    "alter table(#{atom(table)}) do\n" <>
      indent(Enum.map_join(ops, "\n", &render/1), 2) <> "\nend"
  end

  defp render({:create_table, name, table}) do
    {table_opts, id_column} =
      case table["primary_key"] do
        "binary_id" -> {", primary_key: false", ["add :id, :binary_id, primary_key: true"]}
        "string" -> {", primary_key: false", ["add :id, :string, primary_key: true"]}
        "id" -> {"", []}
      end

    columns = for {column, spec} <- Enum.sort(table["columns"]), do: add(column, spec)
    timestamps = if table["timestamps"], do: ["timestamps(type: :utc_datetime_usec)"], else: []

    "create table(#{atom(name)}#{table_opts}) do\n" <>
      indent(Enum.join(id_column ++ columns ++ timestamps, "\n"), 2) <> "\nend"
  end

  defp render({:drop_table, name, _table}), do: "drop table(#{atom(name)})"

  defp render({:rename_table, from, to}),
    do: "rename table(#{atom(from)}), to: table(#{atom(to)})"

  defp render({:rename_column, table, from, to}),
    do: "rename table(#{atom(table)}), #{atom(from)}, to: #{atom(to)}"

  defp render({:add_column, _table, column, spec}), do: add(column, spec)
  defp render({:remove_column, _table, column, _spec}), do: "remove #{atom(column)}"

  defp render({:modify_column, _table, column, spec, old}) do
    "modify #{atom(column)}, #{type(spec)}#{column_opts(spec)}, from: {#{type(old)}#{column_opts(old)}}"
  end

  defp render({:rename_index, table, from, to, index}),
    do: "rename #{index(table, from, index)}, to: #{atom(to)}"

  defp render({:create_index, table, name, index}), do: "create " <> index(table, name, index)
  defp render({:drop_index, table, name, index}), do: "drop " <> index(table, name, index)

  defp add(column, spec), do: "add #{atom(column)}, #{type(spec)}#{column_opts(spec)}"

  defp type(%{"type" => "references", "references" => ref}) do
    type_opt = if ref["type"] == "id", do: "", else: ", type: :#{ref["type"]}"
    "references(#{atom(ref["table"])}#{type_opt}, on_delete: :#{ref["on_delete"]})"
  end

  defp type(%{"type" => type}), do: ":" <> type

  defp column_opts(spec) do
    null = if spec["null"], do: "", else: ", null: false"
    default = if is_nil(spec["default"]), do: "", else: ", default: #{inspect(spec["default"])}"
    null <> default
  end

  defp index(table, name, index) do
    function = if index["unique"], do: "unique_index", else: "index"
    columns = Enum.map_join(index["columns"], ", ", &atom/1)
    "#{function}(#{atom(table)}, [#{columns}], name: #{atom(name)})"
  end

  defp atom(name), do: name |> String.to_atom() |> inspect()

  defp indent(text, spaces) do
    padding = String.duplicate(" ", spaces)

    text
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> padding <> line
    end)
  end
end
