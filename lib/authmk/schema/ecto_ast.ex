defmodule Authmk.Schema.EctoAst do
  @moduledoc false
  # Builds Ecto schema code from resolved models.

  alias Authmk.Schema.{Definition, Field, Model, PrimaryKey}

  @doc "Defines the Ecto schema module for a model that authmk owns."
  @spec define_module(Model.t(), Definition.t(), Macro.Env.t()) :: term()
  def define_module(%Model{owner: :library} = model, definition, env) do
    fields = field_asts(model, definition)
    timestamps = if model.timestamps, do: quote(do: timestamps())

    contents =
      quote do
        @moduledoc "Ecto schema for the `#{unquote(model.key)}` model. Generated by authmk."
        use Ecto.Schema

        @primary_key unquote(Macro.escape(PrimaryKey.attribute(model.primary_key)))
        @timestamps_opts [type: :utc_datetime_usec]

        schema unquote(model.table) do
          unquote_splicing(fields)
          unquote(timestamps)
        end
      end

    Module.create(model.module, contents, Macro.Env.location(env))
  end

  @doc "`field` and `belongs_to` calls for every field of a model."
  @spec field_asts(Model.t(), Definition.t()) :: [Macro.t()]
  def field_asts(model, definition), do: Enum.map(model.fields, &field_ast(&1, definition))

  defp field_ast(%Field{references: nil} = field, _definition) do
    opts =
      [source: field.source, default: field.default, redact: field.redact || nil]
      |> Enum.reject(fn {_key, value} -> is_nil(value) end)

    quote do
      field(
        unquote(field.name),
        unquote(Field.ecto_type(field)),
        unquote(opts)
      )
    end
  end

  defp field_ast(%Field{} = field, definition) do
    target = Definition.model!(definition, field.references)

    opts =
      [
        foreign_key: field.name,
        type: PrimaryKey.ecto_type(target.primary_key),
        source: field.source
      ]
      |> Enum.reject(fn {_key, value} -> is_nil(value) end)

    quote do
      belongs_to(unquote(Field.association(field)), unquote(target.module), unquote(opts))
    end
  end
end
